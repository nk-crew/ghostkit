/**
 * Regenerates the FontAwesome pack in classes/class-icons.php from the
 * @fortawesome/fontawesome-free npm package.
 *
 * Usage: node tools/icons/font-awesome.mjs [version]
 *
 * Saved content may reference an icon by its class name (the `fallback`
 * field), so an icon of the current pack whose class name the new version
 * no longer ships is kept with its current SVG.
 */
import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const VERSION = process.argv[2] || '7.3.1';
const PACKAGE = '@fortawesome/fontawesome-free';
const STYLES = ['brands', 'regular', 'solid'];

const root = path.resolve(
	path.dirname(fileURLToPath(import.meta.url)),
	'../..'
);
const target = path.join(root, 'classes/class-icons.php');
const START = '    /**\n     * Extend icons list with FontAwesome free icons.';

function download(spec) {
	const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'ghostkit-icons-'));
	const file = execFileSync(
		'npm',
		['pack', spec, '--pack-destination', dir, '--silent'],
		{
			encoding: 'utf8',
		}
	)
		.trim()
		.split('\n')
		.pop();
	execFileSync('tar', ['-xzf', path.join(dir, file), '-C', dir]);

	return path.join(dir, 'package');
}

function php(str) {
	return str.replace(/\\/g, '\\\\').replace(/'/g, "\\'");
}

function unphp(str) {
	return str.replace(/\\(['\\])/g, '$1');
}

// Entries of the pack as it is now, read back from the generated PHP.
function parseEntries(source) {
	const re =
		/array\(\n\s*'keys' => '((?:[^'\\]|\\.)*)',\n\s*'svg' => '((?:[^'\\]|\\.)*)',\n(?:\s*'fallback' => '((?:[^'\\]|\\.)*)',\n)?\s*\)/g;

	return [...source.matchAll(re)].map((m) => ({
		keys: unphp(m[1]),
		svg: unphp(m[2]),
		fallback: m[3] === undefined ? undefined : unphp(m[3]),
	}));
}

const pkg = download(`${PACKAGE}@${VERSION}`);
const families = JSON.parse(
	fs.readFileSync(path.join(pkg, 'metadata/icon-families.json'), 'utf8')
);
const license = fs
	.readFileSync(path.join(pkg, 'svgs/brands/font-awesome.svg'), 'utf8')
	.match(/<!--!\s*(.*?)\s*-->/)[1];

const aliases = {};
const entries = [];

Object.keys(families).forEach((name) => {
	const icon = families[name];

	(icon.aliases?.names || []).forEach((alias) => {
		aliases[alias] = name;
	});

	(icon.familyStylesByLicense.free || []).forEach(({ family, style }) => {
		if (family !== 'classic' || !STYLES.includes(style)) {
			return;
		}

		const data = icon.svgs[family][style];

		entries.push({
			keys: name,
			svg: `<svg class="ghostkit-svg-icon ghostkit-svg-icon-fa" aria-hidden="true" role="img" xmlns="http://www.w3.org/2000/svg" viewBox="${data.viewBox.join(' ')}"><path fill="currentColor" d="${data.path}"></path></svg>`,
			fallback: `fa-${style} fa-${name}`,
		});
	});
});

const source = fs.readFileSync(target, 'utf8');
const start = source.indexOf(START);

if (start === -1) {
	throw new Error(`FontAwesome method not found in ${target}`);
}

const fallbacks = new Set(entries.map((entry) => entry.fallback));
const kept = parseEntries(source.slice(start)).filter(
	(entry) => entry.fallback && !fallbacks.has(entry.fallback)
);

entries.push(...kept);

const styleOf = (entry) =>
	STYLES.indexOf(entry.fallback.split(' ')[0].slice(3));
entries.sort(
	(a, b) =>
		styleOf(a) - styleOf(b) ||
		(a.keys < b.keys ? -1 : a.keys > b.keys ? 1 : 0)
);

const list = entries
	.map(
		(entry) => `                array(
                    'keys' => '${php(entry.keys)}',
                    'svg' => '${php(entry.svg)}',
                    'fallback' => '${php(entry.fallback)}',
                ),
`
	)
	.join('');

const method = `${START}
     *
     * Generated by tools/icons/font-awesome.mjs, do not edit by hand.
     * ${license}
     *
     * @param array $icons - icons list.
     *
     * @return array
     */
    public static function add_font_awesome_icons( $icons ) {
        // v${VERSION}
        $icons['font-awesome'] = array(
            'name' => 'FontAwesome',
            'icons' => array(
${list}            ),
        );

        return $icons;
    }
}

new GhostKit_Icons_List();
`;

fs.writeFileSync(target, source.slice(0, start) + method);

const counts = {};
entries.forEach((entry) => {
	const style = entry.fallback.split(' ')[0];
	counts[style] = (counts[style] || 0) + 1;
});

console.log(`FontAwesome ${VERSION}: ${entries.length} icons`, counts);
kept.forEach((entry) => {
	const name = entry.fallback.split(' fa-')[1];
	const now = aliases[name];
	console.log(
		`kept ${entry.fallback}${now ? ` (alias of ${now} in ${VERSION})` : ` (not in ${VERSION} Free)`}`
	);
});
console.log(
	`${path.relative(root, target)}: ${fs.statSync(target).size} bytes`
);
